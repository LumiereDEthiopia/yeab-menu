const DEFAULT_IMAGE = PERFUME_IMAGES.normal;

function bottleIndexFromCode(code: string, count: number): number {
  return code.split('').reduce((sum, char) => sum + char.charCodeAt(0), 0) % count;
}

function getPerfumeImage(seed: PerfumeSeed): string {
  const category = seed.category ?? 'Brand Perfume';
  const gender = seed.gender ?? 'Male';

  if (category === 'Luxury Perfume') {
    const useRed = bottleIndexFromCode(seed.code, 2) === 0;
    return useRed ? PERFUME_IMAGES.luxuryRed : PERFUME_IMAGES.luxuryBlack;
  }

  if (gender === 'Female') {
    return FEMALE_BOTTLES[bottleIndexFromCode(seed.code, FEMALE_BOTTLES.length)];
  }

  if (gender === 'Unisex') {
    return UNISEX_BOTTLES[bottleIndexFromCode(seed.code, UNISEX_BOTTLES.length)];
  }

  return STANDARD_BOTTLES[bottleIndexFromCode(seed.code, STANDARD_BOTTLES.length)];
}

