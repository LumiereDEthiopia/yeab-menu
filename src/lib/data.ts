type PerfumeSeed = {
  code: string;
  name: string;
  brand: string;
  category?: Category;
  price?: number;
  gender?: Gender;
  stockStatus?: StockStatus;
  accords: string[];
  top: string[];
  middle: string[];
  base: string[];
  longevity: string;
  sillage: string;
  dayNight: DayNight;
  seasons: Season[];
};

function makeNotes(names: string[]) {
  return names.map((name) => ({ name, iconUrl: NOTE_ICON }));
}

function makeAccords(names: string[]) {
  return names.map((name, index) => ({
    name,
    value: Math.max(55, 95 - index * 10),
    color: ACCORD_COLORS[name] || '#64748b',
  }));
}

function makePerfume(seed: PerfumeSeed): Perfume {
  const notesText = [
    `top notes of ${seed.top.join(', ')}`,
    `heart notes of ${seed.middle.join(', ')}`,
    `base notes of ${seed.base.join(', ')}`,
  ].join('; ');

  const genderLabel =
    seed.gender === 'Female' ? "women's" : seed.gender === 'Unisex' ? 'unisex' : "men's";

  return {
    id: seed.code.toLowerCase(),
    name: seed.name,
    code: seed.code,
    brand: seed.brand,
    price: seed.price ?? 0,
    gender: seed.gender ?? 'Male',
    category: seed.category ?? 'Brand Perfume',
    stockStatus: seed.stockStatus ?? 'In Stock',
    description: `${seed.name} by ${seed.brand} is a ${genderLabel} fragrance built around ${seed.accords.join(', ')} accords, with ${notesText}.`,
    rating: 4.8,
    mainImage: getPerfumeImage(seed),
    galleryImages: [getPerfumeImage(seed)],
    accords: makeAccords(seed.accords),
    fragranceProfile: {
      longevity: seed.longevity,
      projection: seed.sillage,
      sillage: seed.sillage,
    },
    dayNight: seed.dayNight,
    seasons: seed.seasons,
    notes: {
      top: makeNotes(seed.top),
      middle: makeNotes(seed.middle),
      base: makeNotes(seed.base),
    },
  };
}

