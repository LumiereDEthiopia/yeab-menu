export type Gender = 'Male' | 'Female' | 'Kids' | 'Unisex';
export type DayNight = 'Day' | 'Night' | 'Both';
export type Season = 'Winter' | 'Spring' | 'Summer' | 'Autumn';
export type Category = 'Perfume' | 'Brand Perfume' | 'Luxury Perfume';
export type StockStatus = 'In Stock' | 'Low Stock' | 'Out Stock';

export interface Perfume {
  id: string;
  name: string;
  code: string;
  brand: string;
  price: number;
  gender: Gender;
  category: Category;
  stockStatus: StockStatus;
  description: string;
  rating: number;
  mainImage: string;
  miniImage?: string;
  galleryImages: string[];
  accords: { name: string; value: number; color: string }[];
  fragranceProfile: {
    longevity: string;
    projection: string;
    sillage: string;
  };
  dayNight: DayNight;
  seasons: Season[];
  notes: {
    top: { name: string; iconUrl: string }[];
    middle: { name: string; iconUrl: string }[];
    base: { name: string; iconUrl: string }[];
  };
}

